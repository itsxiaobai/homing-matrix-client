/// 由本機 kv 還原語言偏好（啟動時呼叫；讀取失敗＝維持預設繁中）。
Future<void> loadAppLocale() async {
  try {
    final raw = await AppSettings.get(kAppLocaleKey);
    if (raw == 'en') {
      setAppLocale(AppLocale.en);
    } else if (raw == 'zhTW') {
      setAppLocale(AppLocale.zhTW);
    }
  } catch (_) {
    // 讀取失敗不影響啟動（維持預設）。
  }
}

/// 切換語言並持久化（設定頁使用）。
Future<void> saveAppLocale(AppLocale locale) async {
  setAppLocale(locale);
  try {
    await AppSettings.set(kAppLocaleKey, locale == AppLocale.en ? 'en' : 'zhTW');
  } catch (_) {
    // 寫入失敗不影響當前 session（下次啟動回到預設）。
  }
}
