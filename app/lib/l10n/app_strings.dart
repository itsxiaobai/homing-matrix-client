/// kv key：語言偏好（`'zhTW'`／`'en'`）。
const String kAppLocaleKey = 'app_locale';

/// 支援的語言。
enum AppLocale {
  /// 繁體中文（台灣）——預設。
  zhTW,

  /// 英文。
  en;

  /// 對應的 Flutter `Locale`（供 `MaterialApp.locale` 與
  /// `GlobalMaterialLocalizations` 使用）。
  Locale get flutterLocale => switch (this) {
        AppLocale.zhTW => const Locale('zh', 'TW'),
        AppLocale.en => const Locale('en'),
      };
}

/// 目前語言（**由 [AppLocaleController] 持有**）。
AppLocale _current = AppLocale.zhTW;

/// 語言切換的 notifier（值改變 → 上層重建 → 文字即時更新）。
final ValueNotifier<AppLocale> appLocaleNotifier =
    ValueNotifier<AppLocale>(_current);

/// 設定目前語言（**不負責持久化**；持久化由呼叫端寫入 kv）。
void setAppLocale(AppLocale locale) {
  if (_current == locale) return;
  _current = locale;
  appLocaleNotifier.value = locale;
}

/// 目前語言。
AppLocale get currentAppLocale => _current;

